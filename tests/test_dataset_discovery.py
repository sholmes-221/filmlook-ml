# ---------------------------------------------------------------------------------------------- deduplication
def test_sha256_and_perceptual_duplicates_are_detected(tmp_path):
    from filmlook_ml.datasets.preprocess import hamming, phash, sha256_file
    rng = np.random.default_rng(0); a = (rng.random((256, 256, 3)) * 255).astype(np.uint8)
    im = Image.fromarray(a); p1 = tmp_path / "a.jpg"; im.save(p1, quality=95); p2 = tmp_path / "b.jpg"; im.save(p2, quality=60)
    assert sha256_file(p1) != sha256_file(p2)                                                                      # bytes differ ...
    assert hamming(phash(Image.open(p1)), phash(Image.open(p2))) <= 4                                              # ... but the image is the same
    other = Image.fromarray((rng.random((256, 256, 3)) * 255).astype(np.uint8))
    assert hamming(phash(im), phash(other)) > 10
    (tmp_path / "c.jpg").write_bytes(p1.read_bytes()); assert sha256_file(tmp_path / "c.jpg") == sha256_file(p1)


