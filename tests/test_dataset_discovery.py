# ---------------------------------------------------------------------------------------------- authenticity
def test_authenticity_classes_come_from_evidence_not_text_alone():
    assert D.classify_authenticity({"physical_provenance": "owner's negatives scanned to DNG"})[0] == "A"
    assert D.classify_authenticity({"analog_metadata": "scanner EXIF + uploader stock tag"})[0] == "B"
    assert D.classify_authenticity({"text": "beautiful 35mm film photographs shot on Portra 400"})[0] == "C"      # a claim is not evidence
    assert D.classify_authenticity({"text": "film look presets applied in Capture One to digital photos"})[0] == "D"
    assert D.classify_authenticity({"text": "images generated by stable diffusion"})[0] == "E"
    assert D.classify_authenticity({"synthetic": True, "physical_provenance": "x"})[0] == "E"                     # flags win
    assert D.classify_authenticity({"simulation": True, "analog_metadata": "x"})[0] == "D"
    for cls in ("C", "D", "E"):
        ok, why = D.eligible_for_real_pool({"auth_class": cls, "license_raw": "CC0"}); assert not ok and "class" in why
    assert D.eligible_for_real_pool({"auth_class": "A", "license_raw": "CC BY-NC 4.0"})[0] is False
    assert D.eligible_for_real_pool({"auth_class": "B", "license_raw": "CC BY 2.0"}) == (True, "eligible")
    assert "evaluation-only" in D.eligible_for_real_pool({"auth_class": "A", "license_raw": "CC BY-SA 4.0"})[1]


def test_rank_respects_weights_and_hard_requirements():
    good = {"auth_class": "A", "license_raw": "CC0", "scores": {"diversity": 1, "stock_diversity": 1, "quality": 1, "metadata": 1}}
