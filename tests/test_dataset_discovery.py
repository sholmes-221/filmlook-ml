# ---------------------------------------------------------------------------------------------- registry
def test_registry_keeps_decisions_and_does_not_repeat_searches(reg, monkeypatch):
    calls = []
    def fake_hf(q, limit=50):
        calls.append(q); return [{"key": "hf:x/film-scans", "platform": "hf", "name": "x/film-scans", "url": "u", "license_raw": "cc-by-4.0", "queries": [q]},
                                 {"key": "hf:x/cats", "platform": "hf", "name": "x/cats", "url": "u2", "license_raw": None, "queries": [q]}]
    adapters = {"hf": (fake_hf, 0.0)}; monkeypatch.setattr(D, "HF_TOKENS", ["film", "analog"])
    r1 = D.discover(platforms=("hf",), ttl_days=7, sleep=lambda s: None, adapters=adapters, log=lambda *_: None)
    assert r1["queries_run"] == 2 and r1["new_candidates"] == 1 and "hf:x/cats" not in D.load()["sources"]      # non-film result filtered
    D.set_status("hf:x/film-scans", "rejected", "C", "no provenance")
    r2 = D.discover(platforms=("hf",), ttl_days=7, sleep=lambda s: None, adapters=adapters, log=lambda *_: None)
    assert r2["queries_run"] == 0 and len(calls) == 2                                                           # within TTL: not searched again
    reg_ = D.load(); reg_["searches"] = {k: {"ts": time.time() - 30 * 86400} for k in reg_["searches"]}; D.save(reg_)
    D.discover(platforms=("hf",), ttl_days=7, sleep=lambda s: None, adapters=adapters, log=lambda *_: None)
    assert D.load()["sources"]["hf:x/film-scans"]["status"] == "rejected"                                        # re-found, decision kept
    assert D.seed() >= 20 and D.load()["sources"]["condenast:photovogue"]["status"] == "metadata_only"
    assert D.seed() == 0                                                                                         # idempotent
    assert "Decided sources" in D.report()


