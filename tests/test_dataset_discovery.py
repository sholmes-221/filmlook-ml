# ---------------------------------------------------------------------------------------------- selection + splits
def _cand(pid, uid, stock, w=1600, h=1200):
    return {"photoid": str(pid), "uid": uid, "film_stock": stock, "film_brand": "kodak", "width": w, "height": h}


def test_selection_caps_training_exclusion_and_split_integrity():
    from scripts.ingest_commoncatalog_film import CAPS, half_of, select
    cands = [_cand(i, f"u{i % 10}", "kodak_portra_400") for i in range(400)] + [_cand(1000 + i, "big", "kodak_portra_400") for i in range(50)]
    cands += [_cand(2000, "u1", "kodak_portra_400", w=800), _cand(2001, "u2", None), {**_cand(2002, "u3", None), "conflict": ["a", "b"]}, _cand(1, "u1", "kodak_portra_400")]
    sel = select(cands, exclude_uploaders={"u0"})
    from collections import Counter
    per_up = Counter(c["uid"] for c in sel); per_stock = Counter(c["film_stock"] or "brand_only" for c in sel)
    assert "u0" not in per_up and max(per_up.values()) <= CAPS["per_uploader"] and per_stock["kodak_portra_400"] <= CAPS["per_stock"]
    assert all(min(c["width"], c["height"]) >= 1024 and not c.get("conflict") for c in sel)
    assert len({c["photoid"] for c in sel}) == len(sel)                                                             # no duplicate photo ids
    assert Counter((c["uid"], c["film_stock"]) for c in sel).most_common(1)[0][1] <= CAPS["per_uploader_stock"]
    halves = {u: half_of(u) for u in per_up}; assert set(halves.values()) <= {"analysis", "test"}
    assert all(half_of(u) == halves[u] for u in per_up)                                                              # deterministic: an uploader is never in both halves


