#!/usr/bin/env python
"""Export the style engine to JavaScript and build the single-file bundle.

1. Rarity quantiles from the REFERENCE pool = CommonCatalog originals in the TRAIN split (val/test never used).
2. js/filmlook-style/model-data.js  (profiles, dims, quantiles, thresholds, bilingual texts, optional learned model)
3. js/filmlook-style/dist/filmlook-style.js  (one classic <script>, global `FilmLookStyle`, no eval / WASM)

  python scripts/style_export_js.py [--learned reports/style_learned_model.json]
"""
import argparse
import json
from pathlib import Path

from filmlook_ml import paths as P
from filmlook_ml.datasets.preprocess import read_jsonl
from filmlook_ml.style.engine import model_payload
from filmlook_ml.style.profiles import PROFILES, calibrate_rarity, dims_from_features, profile_evidence

JS = P.ROOT / "js" / "filmlook-style"
MODULES = ["features.js", "engine.js", "model-data.js", "index.js"]


def reference_quantiles() -> tuple[dict, int]:
    man = read_jsonl(P.MANIFESTS / "manifest.jsonl")
    F = json.loads((P.EMBEDDINGS / "style_features.json").read_text())
    ref = [r for r in man if r["edit_type"] == "original" and r["dataset_id"] == "commoncatalog_ccby"
           and r["split"] == "train"]
    scores = {pid: [] for pid in PROFILES}
    for r in ref:
        d = dims_from_features(F[r["sha256"]])
        for pid, p in PROFILES.items():
            scores[pid].append(profile_evidence(d, p["profile"])["score"])
    return calibrate_rarity(scores), len(ref)


def build_bundle() -> Path:
    parts = ["/* FilmLookStyle bundle - generated by scripts/style_export_js.py. ES2017, no dependencies,",
             "   no eval/new Function/WebAssembly/network. Exposes global FilmLookStyle. */",
             "(function (root) {", "'use strict';", "var defs = {}, cache = {};",
             "function req(name) {",
             "  if (cache[name]) return cache[name].exports;",
             "  var module = { exports: {} }; cache[name] = module;",
             "  defs[name](module, module.exports, req); return module.exports;", "}"]
    for m in MODULES:
        src = (JS / m).read_text()
        parts.append(f"defs['./{m}'] = function (module, exports, require) {{\n{src}\n}};")
    parts += ["var api = req('./index.js');", "root.FilmLookStyle = api;",
              "if (typeof module === 'object' && module.exports) module.exports = api;",
              "})(typeof self !== 'undefined' ? self : this);", ""]
    out = JS / "dist" / "filmlook-style.js"
    out.parent.mkdir(exist_ok=True)
    out.write_text("\n".join(parts))
    return out


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--learned", default=None, help="exported learned model JSON (omit for profile-only v1)")
    a = ap.parse_args()
    q, n_ref = reference_quantiles()
    learned = json.loads(Path(a.learned).read_text()) if a.learned else None
    payload = model_payload(q, learned)
    payload["reference_pool"] = {"n": n_ref, "description": "CommonCatalog CC-BY originals, train split"}
    (JS / "model-data.js").write_text("/* generated by scripts/style_export_js.py - do not edit */\n'use strict';\n"
                                      f"module.exports = {json.dumps(payload, ensure_ascii=False, separators=(',', ':'))};\n")
    out = build_bundle()
    print(f"model-data.js {(JS / 'model-data.js').stat().st_size / 1024:.1f} KB; bundle {out} "
          f"{out.stat().st_size / 1024:.1f} KB (reference pool n={n_ref})")


if __name__ == "__main__":
    main()
